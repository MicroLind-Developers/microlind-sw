#!/usr/bin/env python3
"""Generate target declarations without relying on compiler structure packing."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
values = json.loads((root / 'include/abi.json').read_text())
asm = '; Generated by tools/gen_abi.py; edit abi.json.\n'
asm += '\n'.join(f'{key:30} equ {value}' for key, value in values.items()) + '\n'
c = '/* Generated by tools/gen_abi.py; edit abi.json. */\n#ifndef MLOS_SYSCALLS_H\n#define MLOS_SYSCALLS_H\n'
c += '\n'.join(f'#define {key} ({value})' for key, value in values.items())
c += '''
/* Parameters are byte arrays; words use most significant byte first. */
void mlos_put_u16(unsigned char *p, unsigned int value);
/* D is a raw16-bit result. Handles may have bit15 set; SDK kerror() tests errors. */
int mlos_call(unsigned int number, const unsigned char *parameters);
#endif
'''
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
calls = sorted((v,k) for k,v in values.items() if k.startswith('SYS_') and not k.endswith('_PARAMS_SIZE') and 9 <= v <= 45)
params = '; Generated runtime dispatcher parameter lengths; edit abi.json.\n'
params += ''.join('    fcb '+name+'_PARAMS_SIZE\n' for _,name in calls)
for name, content in [('syscalls.inc', asm), ('syscalls.h', c), ('runtime_params.inc', params)]:
    path = root / 'include' / name
    if args.check:
        if path.read_text() != content:
            raise SystemExit(f'{path}: regenerate with tools/gen_abi.py')
    else:
        path.write_text(content)
